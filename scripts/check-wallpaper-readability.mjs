import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import ts from "typescript";
const { outputText } = ts.transpileModule(readFileSync(new URL("../src/lib/wallpaper-readability.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } });
const context = { exports: {}, Uint8ClampedArray };
runInNewContext(outputText, context);
const { relativeLuminance, contrastRatio, assessReadability } = context.exports;
assert.equal(relativeLuminance([0, 0, 0]), 0);
assert.equal(relativeLuminance([255, 255, 255]), 1);
assert.equal(contrastRatio([255, 255, 255], [0, 0, 0]), 21);
assert.equal(contrastRatio([127, 85, 210], [127, 85, 210]), 1);
assert.ok(Math.abs(contrastRatio([119, 119, 119], [255, 255, 255]) - 4.478) < 0.001);
assert.equal(assessReadability(new Uint8ClampedArray([119, 119, 119, 255]), [255, 255, 255], 4.5).coverage, 0);
assert.equal(assessReadability(new Uint8ClampedArray([119, 119, 119, 255]), [255, 255, 255], 3).coverage, 100);
const split = assessReadability(new Uint8ClampedArray([0, 0, 0, 255, 255, 255, 255, 255]), [255, 255, 255], 4.5);
assert.equal(split.coverage, 50);
assert.equal(split.minimum, 1);
assert.equal(split.samples, 2);
assert.throws(() => assessReadability(new Uint8ClampedArray(), [255, 255, 255], 3));
console.log("Readability checks passed: luminance, contrast, unrounded thresholds, mixed backgrounds and invalid input.");
